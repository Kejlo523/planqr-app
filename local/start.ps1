param(
    [ValidateSet('observe', 'attendance')]
    [string]$Mode = 'attendance'
)

$ErrorActionPreference = 'Stop'
$app = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
$db = (Resolve-Path -LiteralPath (Join-Path $app '../planqr-db')).Path
$dockerCommand = Get-Command docker.exe -ErrorAction SilentlyContinue
$docker = if ($dockerCommand) { $dockerCommand.Source } else {
    Join-Path $env:LOCALAPPDATA 'Programs/DockerDesktop/resources/bin/docker.exe'
}

function Invoke-Docker {
    & $docker @args
    if ($LASTEXITCODE -ne 0) { throw 'The Docker command failed.' }
}

function New-LocalSecret {
    $bytes = [byte[]]::new(24)
    $random = [Security.Cryptography.RandomNumberGenerator]::Create()
    try { $random.GetBytes($bytes) } finally { $random.Dispose() }
    return [BitConverter]::ToString($bytes).Replace('-', '').ToLowerInvariant()
}

$engine = Invoke-Docker --context desktop-linux info --format '{{.OSType}}'
if ($engine -ne 'linux') { throw 'Start the local Docker Desktop Linux engine.' }
$envFileDb = Join-Path $db '.env.local'
$envFileApp = Join-Path $app '.env.local'
if (!(Test-Path -LiteralPath $envFileDb)) {
    @("POSTGRES_PASSWORD=$(New-LocalSecret)", 'POSTGRES_PORT=55433') |
        Set-Content -LiteralPath $envFileDb -Encoding ASCII
}
$passwordLine = Get-Content -LiteralPath $envFileDb | Where-Object { $_ -match '^POSTGRES_PASSWORD=[a-f0-9]{48}$' }
if (@($passwordLine).Count -ne 1) { throw 'Use a local PostgreSQL password generated by this script.' }
$databasePassword = $passwordLine.Substring('POSTGRES_PASSWORD='.Length)
$localDatabase = "postgresql://zut:$databasePassword@db:5432/planqr-db-prod"
if (!(Test-Path -LiteralPath $envFileApp)) {
    @(
        'NODE_ENV=development'
        'PORT=9099'
        'DISABLE_HTTPS=true'
        'BACKEND_PUBLIC_URL=https://localhost:8443'
        'CORS_ORIGIN=https://localhost:8443'
        "DATABASE_URL=$localDatabase"
        "JWT_SECRET=$(New-LocalSecret)"
        'ROOT_ADMIN_LOGIN=local-root'
        "ROOT_ADMIN_PASSWORD=$(New-LocalSecret)"
        'LDAP_URL=ldap://127.0.0.1'
        'LDAP_DN=uid=%s,dc=localhost'
        "LDAP_FIXTURE_PASSWORD=$(New-LocalSecret)"
        'ZUT_SCHEDULE_STUDENT_URL=https://plan.zut.edu.pl/schedule_student.php'
        'ZUT_SCHEDULE_URL=https://plan.zut.edu.pl/schedule.php'
        'ZUT_PLAN_BASE_URL=https://plan.zut.edu.pl'
        'FRONTEND_PORT=8443'
        'FRONTEND_BIND_IP=127.0.0.1'
        'BACKEND_INTERNAL_URL=http://backend:9099'
        'PLANQR_CERTS_DIR=./.local/certs'
        'PLANQR_UPLOADS_DIR=./.local/uploads'
        'KANTECH_USER=simulator'
        "KANTECH_PASS=$(New-LocalSecret)"
        'KANTECH_DOOR_IDS=49919,49920'
        "KANTECH_ACTIVE_FROM=$([DateTime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ'))"
        "WORKER_SECRET_TOKEN=$(New-LocalSecret)"
    ) | Set-Content -LiteralPath $envFileApp -Encoding ASCII
}
if ((Get-Content -LiteralPath $envFileApp) -notcontains "DATABASE_URL=$localDatabase") {
    throw 'The local configuration must use the database created by this script.'
}
$localDirectory = Join-Path $app '.local'
$certDirectory = Join-Path $localDirectory 'certs'
New-Item -ItemType Directory -Force -Path $certDirectory,(Join-Path $localDirectory 'uploads') | Out-Null
$cert = Join-Path $certDirectory 'cert.pem'
$key = Join-Path $certDirectory 'cert.key'
if (!(Test-Path -LiteralPath $cert) -or !(Test-Path -LiteralPath $key)) {
    $opensslCommand = Get-Command openssl.exe -ErrorAction SilentlyContinue
    $openssl = if ($opensslCommand) { $opensslCommand.Source } else {
        Join-Path $env:ProgramFiles 'Git/usr/bin/openssl.exe'
    }
    & $openssl req -x509 -newkey rsa:2048 -sha256 -nodes -days 90 -subj '/CN=localhost' -addext 'subjectAltName=DNS:localhost,IP:127.0.0.1' -keyout $key -out $cert
    if ($LASTEXITCODE -ne 0) { throw 'Could not create the local HTTPS certificate.' }
}

$dbCompose = @('--context', 'desktop-linux', 'compose', '-p', 'planqr-db-local', '--env-file', $envFileDb,
    '-f', (Join-Path $db 'docker-compose.yml'), '-f', (Join-Path $db 'compose.local.yml'))
$appCompose = @('--context', 'desktop-linux', 'compose', '-p', 'planqr-app-local', '--env-file', $envFileApp,
    '-f', (Join-Path $app 'docker-compose.yml'), '-f', (Join-Path $app 'compose.local.yml'), '--profile', 'kantech')
$networks = Invoke-Docker --context desktop-linux network ls --filter 'name=^planqr-local$' --format '{{.Name}}'
if ($networks -notcontains 'planqr-local') { Invoke-Docker --context desktop-linux network create planqr-local | Out-Null }

$originalMode = $env:KANTECH_MODE
$originalDatabase = $env:DATABASE_URL
$originalPassword = $env:POSTGRES_PASSWORD
$originalBind = $env:FRONTEND_BIND_IP
$env:KANTECH_MODE = $Mode
$env:DATABASE_URL = $localDatabase
$env:POSTGRES_PASSWORD = $databasePassword
$env:FRONTEND_BIND_IP = '127.0.0.1'
try {
    Invoke-Docker @dbCompose up -d --wait db
    Invoke-Docker @appCompose build backend frontend
    Invoke-Docker @appCompose run --rm --no-deps backend npm run migrate
    $seedAdmin = 'INSERT INTO admins (id, username, "updatedAt") VALUES (''fixture-admin'', ''pilot-admin'', NOW()) ON CONFLICT (username) DO NOTHING'
    Invoke-Docker @dbCompose exec -T db psql -v ON_ERROR_STOP=1 -U zut -d planqr-db-prod -c $seedAdmin
    Invoke-Docker @appCompose run --rm --no-deps -v "$($PSScriptRoot):/fixtures:ro" backend npm run attendance:configure -- /fixtures/assignments.json
    Invoke-Docker @appCompose up -d --wait
} finally {
    $env:KANTECH_MODE = $originalMode
    $env:DATABASE_URL = $originalDatabase
    $env:POSTGRES_PASSWORD = $originalPassword
    $env:FRONTEND_BIND_IP = $originalBind
}
Write-Output 'PlanQR: https://localhost:8443/adminpanel/kantech'
Write-Output "Local LDAP admin: pilot-admin. Password: LDAP_FIXTURE_PASSWORD in $envFileApp"
